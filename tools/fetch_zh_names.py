#!/usr/bin/env python3
"""Generate local Simplified Chinese Pokemon names from PokeAPI CSV data."""
import csv
import io
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
URL = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/'


def rows(filename):
    cache = ROOT / 'tools' / 'cache' / filename
    if not cache.exists():
        request = urllib.request.Request(URL + filename, headers={'User-Agent': 'pokesurvivor/1.0'})
        with urllib.request.urlopen(request, timeout=60) as response:
            data = response.read()
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_bytes(data)
    return list(csv.DictReader(io.StringIO(cache.read_text(encoding='utf-8'))))


def main():
    language = next(row['id'] for row in rows('languages.csv') if row['identifier'] == 'zh-hans')
    names = {int(row['pokemon_species_id']): row['name'] for row in rows('pokemon_species_names.csv')
             if row['local_language_id'] == language}
    source = (ROOT / 'js/data/pokedex.js').read_text(encoding='utf-8')
    pokemon = [json.loads(line.strip().rstrip(',')) for line in source.splitlines()
               if re.match(r'\s*\{"dex":', line)]
    missing = [p['dex'] for p in pokemon if p['dex'] not in names]
    if missing:
        raise ValueError(f'Missing Chinese names: {missing}')
    dictionary = {p['name']: names[p['dex']] for p in pokemon}
    output = ('/* Generated by tools/fetch_zh_names.py. Do not edit by hand.\n'
              ' * Source: https://github.com/PokeAPI/pokeapi/blob/master/data/v2/csv/pokemon_species_names.csv\n'
              ' * Names are local; gameplay does not request translations.\n'
              ' */\nG.I18n.add(' + json.dumps(dictionary, ensure_ascii=False, indent=2) + ", 'zh-CN');\n")
    (ROOT / 'js/data/names-zh-CN.js').write_text(output, encoding='utf-8')
    print(f'Generated {len(dictionary)} Chinese Pokemon names.')


if __name__ == '__main__':
    main()
